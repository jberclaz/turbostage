"""Generate turbostage/_igdb_credentials.py from the environment.

Release builds run this before PyInstaller so the IGDB (Twitch) app
credentials ship in the binaries without being committed to the repository:

    IGDB_CLIENT_ID=... IGDB_CLIENT_SECRET=... python scripts/write_igdb_credentials.py
"""

import os
import sys

TARGET = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "turbostage", "_igdb_credentials.py")


def main() -> int:
    client_id = os.environ.get("IGDB_CLIENT_ID", "").strip()
    client_secret = os.environ.get("IGDB_CLIENT_SECRET", "").strip()
    if not client_id or not client_secret:
        print("error: IGDB_CLIENT_ID and IGDB_CLIENT_SECRET must both be set", file=sys.stderr)
        return 1
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write("# Generated by scripts/write_igdb_credentials.py; do not commit.\n")
        f.write(f"CLIENT_ID = {client_id!r}\n")
        f.write(f"CLIENT_SECRET = {client_secret!r}\n")
    print(f"Wrote IGDB credentials to {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
